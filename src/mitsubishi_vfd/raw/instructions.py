
from enum import Enum

class MitsubishiVFD_InstructionCode(Enum):
    OPERATION_MODE_READ = 0x7B
    OPERATION_MODE_WRITE = 0xFB
    MONITOR_OUTPUT_FREQUENCY_SPEED = 0x6F # depends on parameter setting, see manual
    MONITOR_OUTPUT_CURRENT = 0x70
    MONITOR_OUTPUT_VOLTAGE = 0x71
    MONITOR_SPECIAL = 0x72
    MONITOR_SPECIAL_SELECT = 0x73
    FAULTS_1_2 = 0x74
    FAULTS_3_4 = 0x75
    FAULTS_5_6 = 0x76
    FAULTS_7_8 = 0x77
    RUN_COMMAND_EXTENDED = 0xF9
    RUN_COMMAND = 0xFA
    INVERTER_STATUS_EXTENDED = 0x79
    INVERTER_STATUS = 0x7A
    FREQUENCY_SETPOINT_RAM_READ = 0x6D
    FREQUENCY_SETPOINT_EEPROM_READ = 0x6E
    FREQUENCY_SETPOINT_RAM_WRITE = 0xED
    FREQUENCY_SETPOINT_EEPROM_WRITE = 0xEE
    INVERTER_RESET = 0xFD
    FAULTS_CLEAR_ALL = 0xF4
    PARAMETER_CLEAR_ALL = 0xFC
    # PARAMETERS 0x00..0x63 and 0x80..0xE3
    PARAMETER_NUMBER_EXTENSION_READ = 0x7F
    PARAMETER_NUMBER_EXTENSION_WRITE = 0xFF
    CALIBRATION_PARAMETER_EXTRA_READ = 0x6C
    CALIBRATION_PARAMETER_EXTRA_WRITE = 0xEC

MITSUBISHIVFD_PARAMETER_MASK_WRITE = 0x80

